const COLS = 16;
const ROWS = 11;

function BarGlyph({ rows }: { rows?: string[] }) {
  const bars: { x: number; y: number; w: number }[] = [];
  rows?.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) bars.push({ x: run.index ?? 0, y, w: run[0].length });
  });
  return (
    <svg
      viewBox={`0 0 ${COLS * 10} ${ROWS * 10}`}
      aria-hidden
      className="-mb-0.5 block h-auto w-full fill-paper [mask-image:linear-gradient(var(--ds-color-black)_45%,color-mix(in_srgb,var(--ds-color-black)_55%,transparent))]"
    >
      {bars.map((b) => (
        <rect key={`${b.x}-${b.y}`} x={b.x * 10} y={b.y * 10 + 2} width={b.w * 10} height={6} />
      ))}
    </svg>
  );
}

function StripedWordmark({ text = "AGENTCARD", label, className, style, ...props }: Omit<React.ComponentProps<"div">, "children"> & { text?: string; label?: string }) {
  const letters = [...text.toUpperCase()];
  return (
    <div
      role="img"
      aria-label={label ?? text}
      data-slot="striped-wordmark"
      className={cn("grid w-full", className)}
      style={{ gridTemplateColumns: `repeat(${letters.length}, minmax(0, 1fr))`, ...style }}
      {...props}
    >
      {letters.map((letter, i) => (
        <div
          key={i}
          className="grid items-end border-l border-line-on-brand-strong px-[clamp(--spacing(0.75),0.8vw,--spacing(3.5))] pt-[clamp(--spacing(5),3vw,--spacing(12))] pb-[clamp(0rem,calc((87.5rem-100vw)*0.145),--spacing(19))] first:border-l-0"
        >
          <BarGlyph rows={GLYPHS[letter]} />
        </div>
      ))}
    </div>
  );
}

export { StripedWordmark };
